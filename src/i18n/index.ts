/** English is the main language, French the second one (served under /fr). */
export type Lang = "en" | "fr";

export const langs: Lang[] = ["en", "fr"];

/** Prefix an internal path for a language: "/work" → "/fr/work", "/#path" → "/fr#path". */
export function localize(lang: Lang, path: string) {
  if (lang === "en") return path;
  if (path === "/") return "/fr";
  if (path.startsWith("/#")) return "/fr" + path.slice(1);
  return "/fr" + path;
}

/** The same page in the other language. */
export function switchPath(pathname: string, to: Lang) {
  const bare = pathname.replace(/^\/fr(?=\/|$)/, "") || "/";
  return localize(to, bare);
}

export const langFromPath = (pathname: string): Lang => (/^\/fr(\/|$)/.test(pathname) ? "fr" : "en");

